import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const core=fs.readFileSync('js/01-core.js','utf8'),feed=fs.readFileSync('js/05-feed.js','utf8');
const now=Date.now(),old=now-17*864e5,recent=now-864e5;
const photo=t=>'owner/ph-'+t.toString(36)+'-test.jpg';
const rows=[{id:'old-updated',placeId:'same',createdAt:old,updatedAt:now,visibility:'public',photos:[photo(old),photo(now)]},{id:'yesterday',placeId:'same',createdAt:recent,visibility:'public',photos:['legacy.jpg']},{id:'private',placeId:'same',createdAt:now,visibility:'private',photos:['private.jpg']}];
const ctx=vm.createContext({Date,state:{lang:'zh',homeMode:'all',homeDays:7,homeSort:'latest'},store:{reviews:()=>rows},placeById:()=>({mode:'food'}),esc:s=>String(s),t:(k)=>k});
vm.runInContext(core.slice(core.indexOf('  function timeAgo('),core.indexOf('  function safeURL(')),ctx);
vm.runInContext(feed.slice(feed.indexOf('  function homeTime('),feed.indexOf('  function homeSelect(')),ctx);
assert.equal(vm.runInContext('homeReviews()[0].id',ctx),'old-updated');
assert.equal(vm.runInContext('homeReviews().length',ctx),2);
ctx.r=rows[0];assert.match(vm.runInContext('reviewTimeLabel(r)',ctx),/到访 .*更新于/);
assert.equal(rows[0].createdAt,old);
ctx.r={createdAt:old,photos:[photo(now)]};assert.equal(vm.runInContext('reviewActivityAt(r)',ctx),now);
ctx.pid=photo(now);assert.match(vm.runInContext('photoDateHTML(pid,r)',ctx),/到访/);
ctx.pid='owner/ph-'+now.toString(36)+'-t'+recent.toString(36)+'.jpg';assert.match(vm.runInContext('photoDateHTML(pid,r)',ctx),/拍摄/);
ctx.pid='legacy.jpg';assert.match(vm.runInContext('photoDateHTML(pid,r)',ctx),/到访/);
ctx.pid=photo(now+5*864e5);assert.equal(vm.runInContext('photoUploadedAt(pid)',ctx),0);
assert.match(feed,/photoDateHTML\(id, r\)/);
console.log('Passed: updated public visit returns to recent feed, private excluded, same-place visits coexist, original visit date preserved, legacy upload fallback and honest photo date labels.');
